"""Write core/ui/product_mark.h, Crucible's boot mark, from its SVG sources (docs/crucible/brand/).

    tools/crucible_mark.py [--check]

The splash draws the mark per pixel (ui_screens.c mark_color) so it scales to every display with no bitmap. This turns
each SVG path (absolute M H V L Q Z only, fill-rule evenodd) into polygons on a 1/16 unit grid; quadratic curves are
flattened into short lines. The color mark is hot-core (body and flame); the 1 bpp mark is single-cut (one ink shape).
--check fails when the header is out of date.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAND = os.path.join(ROOT, "docs", "crucible", "brand")
OUT = os.path.join(ROOT, "core", "ui", "product_mark.h")
SCALE = 16		# grid units per SVG unit
CURVE_STEPS = 6


def paths(svg):
    return re.findall(r'<path fill="(#[0-9A-Fa-f]{6})" fill-rule="evenodd" d="([^"]+)"', svg)


def contours(d):
    toks = re.findall(r"[MHVLQZ]|-?\d+(?:\.\d+)?", d)
    out, cur, x, y, i = [], [], 0.0, 0.0, 0
    num = lambda: float(toks[i])
    cmd = None
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd == "Z":
                if cur:
                    out.append(cur)
                cur = []
            continue
        if cmd == "M":
            if cur:
                out.append(cur)
            x, y = num(), float(toks[i + 1]); i += 2
            cur = [(x, y)]
            cmd = "L"
        elif cmd == "L":
            x, y = num(), float(toks[i + 1]); i += 2
            cur.append((x, y))
        elif cmd == "H":
            x = num(); i += 1
            cur.append((x, y))
        elif cmd == "V":
            y = num(); i += 1
            cur.append((x, y))
        elif cmd == "Q":
            cx, cy, ex, ey = (float(toks[i + k]) for k in range(4)); i += 4
            for s in range(1, CURVE_STEPS + 1):
                t_ = s / CURVE_STEPS
                a, b, c = (1 - t_) ** 2, 2 * (1 - t_) * t_, t_ * t_
                cur.append((a * x + b * cx + c * ex, a * y + b * cy + c * ey))
            x, y = ex, ey
        else:
            raise ValueError("unsupported path data near %r" % t)
    if cur:
        out.append(cur)
    return out


def table(name, d):
    pts, starts = [], []
    for c in contours(d):
        starts.append(len(pts))
        pts += [(round(px * SCALE), round(py * SCALE)) for px, py in c]
    starts.append(len(pts))
    body = ", ".join("{ %d, %d }" % p for p in pts)
    lines = ["static const short %s_pt[][2] = { %s };" % (name, body),
             "static const unsigned char %s_start[] = { %s };" % (name, ", ".join(map(str, starts)))]
    return lines


def rgb565(h):
    r, g, b = int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)
    return "RGB565(%d, %d, %d)" % (r, g, b)


def generate():
    color = paths(open(os.path.join(BRAND, "mark-hot-core.svg")).read())
    mono = paths(open(os.path.join(BRAND, "mark-single-cut.svg")).read())
    if len(color) != 2 or len(mono) != 1:
        raise ValueError("expected two color paths (body, flame) and one mono path")
    # REUSE-IgnoreStart: the generated file's own header, not this file's
    out = ["// SPDX-License-Identifier: MIT",
           "// Copyright (c) 2026 David Behnke",
           # REUSE-IgnoreEnd
           "// Crucible's boot mark, generated by tools/crucible_mark.py from docs/crucible/brand/: do not edit. Included",
           "// by ui_screens.c only. Polygons on a 1/16 grid of the 70x80 SVG box, filled even-odd.",
           "#ifndef PRODUCT_MARK_H", "#define PRODUCT_MARK_H", ""]
    out += table("pm_body", color[0][1]) + table("pm_flame", color[1][1]) + table("pm_mono", mono[0][1])
    out += ["static const color_t PM_BODY = %s, PM_FLAME = %s;" % (rgb565(color[0][0]), rgb565(color[1][0])), ""]
    out += ["""// Whether u,v (grid units) is inside the shape: even-odd over every contour
static bool pm_inside(const short (*pt)[2], const unsigned char *start, int contours, int u, int v)
{
	bool in = false;
	for (int c = 0; c < contours; c++) {
		for (int i = start[c], j = start[c + 1] - 1; i < start[c + 1]; j = i++) {
			int yi = pt[i][1], yj = pt[j][1];
			if ((yi > v) != (yj > v) && u < pt[j][0] + (long)(pt[i][0] - pt[j][0]) * (v - yj) / (yi - yj))
				in = !in;
		}
	}
	return in;
}

#define PM_CONTOURS(name) ((int)sizeof name##_start - 1)

// The mark's color at a point of the splash's 1024 grid (ui_screens.c mark_color: 964 tall, centered 512,512), or -1
// for the background. On 1 bpp the single-cut shape in ink; otherwise hot-core's body with the flame over it
static int product_mark_color(int X, int Y, bool mono, color_t ink)
{
	int u = 35 * 16 + (X - 512) * 1280 / 964, v = 40 * 16 + (Y - 512) * 1280 / 964;
	if (u < 0 || u >= 70 * 16 || v < 0 || v >= 80 * 16)
		return -1;
	if (mono)
		return pm_inside(pm_mono_pt, pm_mono_start, PM_CONTOURS(pm_mono), u, v) ? ink : -1;
	if (pm_inside(pm_flame_pt, pm_flame_start, PM_CONTOURS(pm_flame), u, v))
		return PM_FLAME;
	return pm_inside(pm_body_pt, pm_body_start, PM_CONTOURS(pm_body), u, v) ? PM_BODY : -1;
}

#endif"""]
    return "\n".join(out) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            print("crucible_mark: %s is out of date: run tools/crucible_mark.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("crucible_mark: current")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("crucible_mark: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
